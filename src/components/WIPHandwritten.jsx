// Mask strokes are plain M/L polylines, so their length is just the sum of the segments
const polylineLength = (d) => {
    const n = d.match(/[\d.]+/g).map(Number)
    let length = 0
    for (let i = 2; i < n.length; i += 2) length += Math.hypot(n[i] - n[i - 2], n[i + 1] - n[i - 1])
    return length
}

const LETTERS = Object.entries(STROKES).map(([letter, strokes]) => ({
    ink: new Path2D(INK[letter]),
    strokes: strokes.map(([start, end, width, d, clip]) => ({
        start, end, width, clip: CLIPS[clip], path: new Path2D(d), length: polylineLength(d),
    })),
}))

const DURATION = Math.max(...LETTERS.flatMap((l) => l.strokes.map((s) => s.end)))

// Ink revealed by the pen so far = mask strokes drawn up to time t, clipped to each letter's ink shape
function draw(ctx, t, color) {
    const { width, height } = ctx.canvas
    ctx.setTransform(1, 0, 0, 1, 0, 0)
    ctx.clearRect(0, 0, width, height)
    ctx.setTransform(width / VIEW_W, 0, 0, width / VIEW_W, 0, 0)
    ctx.strokeStyle = color
    ctx.lineCap = 'round'
    ctx.lineJoin = 'round'

    for (const { ink, strokes } of LETTERS) {
        ctx.save()
        ctx.clip(ink)
        for (const s of strokes) {
            const progress = Math.min((t - s.start) / (s.end - s.start), 1)
            if (progress <= 0) continue // a zero-length dash would still paint a round-cap dot
            ctx.save()
            if (s.clip) ctx.clip(s.clip)
            ctx.lineWidth = s.width
            ctx.setLineDash([s.length * progress, s.length])
            ctx.stroke(s.path)
            ctx.restore()
        }
        ctx.restore()
    }
}

export default function WIPHandwritten({ className = '' }) {
    const canvas = useRef(null)

    useGSAP(() => {
        const el = canvas.current
        const ctx = el.getContext('2d')
        const pen = { t: 0 }
        let color

        const resize = () => {
            const width = Math.round(el.clientWidth * window.devicePixelRatio)
            el.width = width
            el.height = Math.round((width * VIEW_H) / VIEW_W)
            color = getComputedStyle(el).color
            draw(ctx, pen.t, color)
        }
        const observer = new ResizeObserver(resize)
        observer.observe(el)

        if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
            pen.t = DURATION
        } else {
            // Strokes progress linearly in time (one continuous pen line); easing the whole pass
            // lets the pen accelerate in and settle out, once.
            gsap.to(pen, { t: DURATION, duration: DURATION, ease: 'power1.inOut', onUpdate: () => draw(ctx, pen.t, color) })
        }
        resize()

        return () => observer.disconnect()
    })

    return <canvas ref={canvas} width={VIEW_W} height={VIEW_H} role="img" aria-label="wip" className={className} />
}
